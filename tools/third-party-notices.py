#!/usr/bin/env python3
"""Generate the third-party notices shipped with the ferx R package (#773).

    tools/third-party-notices.py            rewrite inst/THIRD-PARTY-NOTICES.txt
    tools/third-party-notices.py --check    exit 1 if that file is stale

The package's compiled library (src/rust, a staticlib linked into ferx.so)
statically links ferx-core and ferx-tools (MIT), ferx-search
(LGPL-3.0-or-later) and every crate they depend on, including the NLopt C
library. Their licenses require the notices to travel with the compiled code,
so this file is installed with the package (system.file("THIRD-PARTY-NOTICES.txt",
package = "ferx")), shipped in the source tarball, and copied into the Docker
images.

The list is every crate the staticlib links: the normal-dependency closure of
the `ferx` glue crate in src/rust/Cargo.lock with all its features on (so the
file covers every feature set a build can choose, CARGO_FEATURES in
src/Makevars included) and across all target platforms (so the file does not
depend on the machine that generates it), minus proc-macro crates and build
dependencies, which run at compile time and are not shipped. Each crate's own
license files (LICENSE*, COPYING*, NOTICE*, COPYRIGHT*) are copied verbatim;
identical texts are printed once.

Crate metadata is not the whole story for vendored C code, so `VENDORED` names
extra files to copy. NLopt is the case that matters: the `nlopt` crate declares
only MIT, but the C library it compiles in includes Luksan's routines (L-BFGS
among them), which are LGPL-2.1-or-later, and that makes the compiled library
LGPL by NLopt's own COPYING. This mirrors ferx-core's
tools/third-party-notices.py, which writes the same notices for the `ferx` CLI.

Reads the revision Cargo.lock pins (`cargo metadata --locked`, no sibling
patch), so a local ../ferx-core checkout never leaks into the file. Needs the
dependencies in the cargo registry; `cargo metadata` fetches them.
"""

import glob
import hashlib
import json
import os
import re
import subprocess
import sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RUST_DIR = os.path.join(REPO, "src", "rust")
OUT = os.path.join(REPO, "inst", "THIRD-PARTY-NOTICES.txt")
LGPL21 = os.path.join(REPO, "inst", "licenses", "LGPL-2.1.txt")
ROOT_PACKAGE = "ferx"
LICENSE_FILE = re.compile(r"^(LICEN[CS]E|COPYING|NOTICE|COPYRIGHT|UNLICENSE)", re.I)

# Crate name -> (note, globs relative to the crate root) for vendored code whose
# terms crate metadata does not state.
VENDORED = {
    "nlopt": (
        "The `nlopt` crate declares MIT, but it compiles in the NLopt C library\n"
        "including the Luksan routines (src/algs/luksan), which are licensed\n"
        "LGPL-2.1-or-later. By NLopt's own COPYING, the compiled library is\n"
        "therefore governed by the LGPL. The NLopt copyright and license files\n"
        "follow; the LGPL-2.1 text is reproduced at the end of this file.",
        ["nlopt-*/COPYING", "nlopt-*/COPYRIGHT", "nlopt-*/src/algs/*/COPYING",
         "nlopt-*/src/algs/*/COPYRIGHT"],
    ),
}

HEADER = """\
Third-party notices for the ferx R package
==========================================

Generated by tools/third-party-notices.py from src/rust/Cargo.lock. Do not edit.

The R code and the Rust glue of the ferx package are MIT-licensed (LICENSE).
Its compiled library statically links the crates listed below, among them
ferx-core and ferx-tools (MIT) and ferx-search (LGPL-3.0-or-later). COPYRIGHTS
in this directory summarises the licenses and says how to rebuild the package
with a modified ferx-search; the LGPL-3.0, GPL-3.0 and LGPL-2.1 texts are in
licenses/.

ferx-core, ferx-tools and ferx-search are built from the ferx-core repository
at the commit src/rust/Cargo.lock pins, which is their complete source:

  {ferx_core_source}

Crates linked into the compiled package (name, version, declared license):
"""


def cargo_metadata():
    out = subprocess.run(
        ["cargo", "metadata", "--format-version", "1", "--locked", "--all-features"],
        cwd=RUST_DIR, check=True, capture_output=True, text=True,
    ).stdout
    return json.loads(out)


def shipped_packages(meta):
    """Normal-dependency closure of ROOT_PACKAGE, excluding proc macros."""
    pkgs = {p["id"]: p for p in meta["packages"]}
    nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
    members = set(meta["workspace_members"])
    root = next(i for i, p in pkgs.items() if p["name"] == ROOT_PACKAGE and i in members)

    def is_proc_macro(pkg):
        return any("proc-macro" in t["kind"] for t in pkg["targets"])

    seen, stack = set(), [root]
    while stack:
        node = nodes[stack.pop()]
        for dep in node["deps"]:
            if not any(k["kind"] is None for k in dep["dep_kinds"]):
                continue  # dev- or build-only edge
            if dep["pkg"] in seen or is_proc_macro(pkgs[dep["pkg"]]):
                continue
            seen.add(dep["pkg"])
            stack.append(dep["pkg"])
    shipped = [pkgs[i] for i in seen if i not in members]
    return sorted(shipped, key=lambda p: (p["name"], p["version"]))


def license_files(pkg):
    root = os.path.dirname(pkg["manifest_path"])
    files = [f for f in os.listdir(root)
             if LICENSE_FILE.match(f) and os.path.isfile(os.path.join(root, f))]
    if pkg.get("license_file"):
        files.append(pkg["license_file"])
    for pattern in VENDORED.get(pkg["name"], ("", []))[1]:
        files += [os.path.relpath(f, root) for f in glob.glob(os.path.join(root, pattern))]
    return root, sorted(set(os.path.normpath(f) for f in files))


def read_text(path):
    with open(path, encoding="utf-8", errors="replace") as fh:
        return fh.read().replace("\r\n", "\n").rstrip() + "\n"


def render(meta):
    pkgs = shipped_packages(meta)
    for name in ("ferx-core", "ferx-tools", "ferx-search", "nlopt"):
        if not any(p["name"] == name for p in pkgs):
            sys.exit(f"third-party-notices: {name} is not in the linked closure of "
                     f"{ROOT_PACKAGE}; update this script with the dependency change")
    revs = sorted({p["source"].split("#")[-1] for p in pkgs
                   if p["name"] in ("ferx-core", "ferx-tools", "ferx-search")
                   and (p.get("source") or "").startswith("git+")})
    if len(revs) != 1:
        sys.exit("third-party-notices: expected ferx-core, ferx-tools and ferx-search "
                 f"on one pinned git revision, got {revs or 'none'} "
                 "(tools/check-ferx-core-pin.sh says why)")
    source = f"https://github.com/FeRx-NLME/ferx-core/tree/{revs[0]}"
    lines = [HEADER.replace("{ferx_core_source}", source)]
    for p in pkgs:
        lines.append(f"  {p['name']} {p['version']}  {p.get('license') or '(see files)'}")
    lines.append("")

    texts = {}  # sha -> (text, [labels])
    per_pkg = []
    for p in pkgs:
        root, files = license_files(p)
        shas = []
        for f in files:
            text = read_text(os.path.join(root, f))
            sha = hashlib.sha256(text.encode()).hexdigest()[:12]
            texts.setdefault(sha, (text, []))[1].append(f"{p['name']} {p['version']}: {f}")
            shas.append(sha)
        per_pkg.append((p, shas))

    lines.append("Per-crate notes and license texts")
    lines.append("---------------------------------")
    lines.append("")
    for p, shas in per_pkg:
        lines.append(f"* {p['name']} {p['version']} ({p.get('license') or 'see files'})")
        if p.get("repository"):
            lines.append(f"  {p['repository']}")
        note = VENDORED.get(p["name"], ("",))[0]
        if note:
            lines += ["  " + n for n in note.splitlines()]
        if shas:
            lines.append("  texts: " + ", ".join(f"[{s}]" for s in shas))
        else:
            authors = ", ".join(re.sub(r"\s*<[^>]*>", "", a) for a in p["authors"])
            lines.append("  The crate ships no license file. It is distributed under its")
            lines.append("  declared license above" + (f", copyright {authors}" if authors else "")
                         + "; the")
            lines.append("  standard text of each license named appears below under other crates.")
    lines.append("")

    for sha, (text, labels) in sorted(texts.items(), key=lambda kv: kv[1][1][0]):
        lines.append("=" * 78)
        lines.append(f"[{sha}]")
        lines += labels
        lines.append("=" * 78)
        lines.append(text)

    lines.append("=" * 78)
    lines.append("GNU Lesser General Public License, version 2.1 (NLopt / Luksan)")
    lines.append("=" * 78)
    lines.append(read_text(LGPL21))
    return "\n".join(lines)


def main():
    check = sys.argv[1:] == ["--check"]
    if sys.argv[1:] not in ([], ["--check"]):
        sys.exit(__doc__)
    text = render(cargo_metadata()).rstrip() + "\n"
    if check:
        current = read_text(OUT) if os.path.exists(OUT) else ""
        if current != text:
            sys.exit("third-party-notices: inst/THIRD-PARTY-NOTICES.txt is stale; "
                     "run tools/third-party-notices.py")
        return
    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write(text)


if __name__ == "__main__":
    main()
